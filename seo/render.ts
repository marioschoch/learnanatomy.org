/** Pages of one system as a tree: children are the pages whose parent (last ancestor) is the page. */
function systemTree(ctx: RenderContext, lang: PageLang, system: SystemId): { html: string; count: number } {
  const pages = ctx.site.pages.filter((p) => p.system === system);
  const kids = new Map<string | undefined, Page[]>();
  for (const p of pages) {
    const parent = p.ancestors[p.ancestors.length - 1];
    const key = parent && ctx.site.bySlug.get(parent)?.system === system ? parent : undefined;
    kids.set(key, [...(kids.get(key) ?? []), p]);
  }
  const sortByName = (list: Page[]) =>
    [...list].sort((a, b) => primaryName(a.names, lang).localeCompare(primaryName(b.names, lang), lang));
  const seen = new Set<string>();
  const render = (list: Page[]): string =>
    `<ul>${sortByName(list)
      .filter((p) => !seen.has(p.slug) && seen.add(p.slug))
      .map((p) => {
        const sub = kids.get(p.slug);
        const second = secondaryName(p.names, lang);
        return `<li>${link(ctx, lang, p.slug)}${second ? ` <small>${esc(second)}</small>` : ''}${sub ? render(sub) : ''}</li>`;
      })
      .join('')}</ul>`;
  const html = render(kids.get(undefined) ?? []).replace(/^<ul>/, '<ul class="tree">');
  return { html, count: pages.length };
}

export function renderSystemIndex(system: SystemId, lang: PageLang, ctx: RenderContext): string {
  const label = systemLabel(lang, system);
  const { html, count } = systemTree(ctx, lang, system);
  const path = systemUrl(lang, system);
  const body = `<nav class="crumbs" aria-label="Breadcrumb"><ol><li><a href="/${lang}/">${esc(
    s(lang, 'allStructures'),
  )}</a></li></ol></nav>
<h1>${esc(label)}</h1>
<p>${esc(s(lang, 'systemIntro', { count }))} <a href="/">${esc(s(lang, 'toAtlas'))} →</a></p>
${html}`;
  return layout(
    {
      lang,
      title: `${s(lang, 'systemTitle', { system: label })} | ${APP_NAME}`,
      description: truncate(
        `${s(lang, 'systemTitle', { system: label })}. ${s(lang, 'homeDescription')}`,
        200,
      ),
      path,
      alternates: { en: systemUrl('en', system), de: systemUrl('de', system) },
    },
    body,
    ctx,
  );
}

/** Systems that have pages, in the manifest's order. */
export function systemsWithPages(site: Site): SystemId[] {
  const used = new Set(site.pages.map((p) => p.system));
  return site.data.manifest.systems.map((sys) => sys.id).filter((id) => used.has(id));
}

