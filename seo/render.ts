function link(ctx: RenderContext, lang: PageLang, slug: string): string {
  const p = ctx.site.bySlug.get(slug)!;
  return `<a href="${pageUrl(lang, slug)}" lang="${nameLang(p.names, lang)}">${esc(primaryName(p.names, lang))}</a>`;
}

function linkList(ctx: RenderContext, lang: PageLang, slugs: string[]): string {
  const sorted = [...slugs].sort((a, b) =>
    primaryName(ctx.site.bySlug.get(a)!.names, lang).localeCompare(
      primaryName(ctx.site.bySlug.get(b)!.names, lang),
      lang,
    ),
  );
  return `<ul class="links">${sorted.map((sl) => `<li>${link(ctx, lang, sl)}</li>`).join('')}</ul>`;
}

function refList(ctx: RenderContext, lang: PageLang, refs: Ref[]): string {
  const items = refs
    .map((r) => ({ r, name: primaryName(r.names, lang) }))
    .sort((a, b) => a.name.localeCompare(b.name, lang))
    .map(({ r, name }) =>
      r.slug
        ? `<li>${link(ctx, lang, r.slug)}</li>`
        : `<li lang="${nameLang(r.names, lang)}">${esc(name)}</li>`,
    );
  return `<ul class="links">${items.join('')}</ul>`;
}

function describe(page: Page, lang: PageLang): string {
  const lead = lang === 'en' ? firstParagraph(page.definition) : undefined;
  if (lead) return truncate(lead, 158);
  const name = secondaryName(page.names, lang)
    ? `${primaryName(page.names, lang)} (${secondaryName(page.names, lang)})`
    : primaryName(page.names, lang);
  const where = [
    systemLabel(lang, page.system),
    ...page.regions.slice(0, 2).map((r) => regionLabel(lang, r)),
  ];
  return truncate(s(lang, 'describe', { name, where: where.join(', ') }), 200);
}

function definitionSection(def: Definition, lang: PageLang): string {
  const t = UI[lang].info;
  const { blocks, more } = excerpt(def);
  const html = blocks
    .map((b) =>
      b.kind === 'p'
        ? `<p>${esc(b.text)}</p>`
        : b.kind === 'h'
          ? `<h3>${esc(b.text)}</h3>`
          : `<ul>${b.items.map((i) => `<li>${esc(i)}</li>`).join('')}</ul>`,
    )
    .join('\n');
  const textLang = def.text.en ? 'en' : (Object.keys(def.text)[0] ?? 'en');
  const source = def.sourceUrl
    ? `<a href="${esc(def.sourceUrl)}" rel="nofollow noopener">${esc(def.source)}</a>`
    : esc(def.source);
  const url = licenseUrl(def.license);
  const license = url
    ? `<a href="${url}" rel="license">${esc(licenseLabel(def.license))}</a>`
    : esc(licenseLabel(def.license));
  return `<section aria-labelledby="def">
<h2 id="def">${esc(t.definition)}${def.reviewed ? '' : `<span class="badge" title="${esc(t.unreviewedHint)}">${esc(t.unreviewed)}</span>`}</h2>
${lang !== textLang ? `<p class="note">${esc(t.definitionEnglishOnly)}</p>` : ''}
<div lang="${textLang}">
${html}
</div>
${more && def.sourceUrl ? `<p><a href="${esc(def.sourceUrl)}" rel="nofollow noopener">${esc(s(lang, 'readMore', { source: def.source }))} →</a></p>` : ''}
<p class="note">${esc(t.source)}: ${source} · ${esc(t.licenseText)}: ${license}${def.reviewed ? '' : ` · ${esc(t.unreviewedHint)}`}</p>
</section>`;
}

export function renderPage(page: Page, lang: PageLang, ctx: RenderContext): string {
  const t = UI[lang];
  const { site } = ctx;
  const name = primaryName(page.names, lang);
  const second = secondaryName(page.names, lang);
  const fullName = second ? `${name} (${second})` : name;
  const path = pageUrl(lang, page.slug);
  const alternates = { en: pageUrl('en', page.slug), de: pageUrl('de', page.slug) };

  const crumbs: [string, string][] = [
    [`/${lang}/`, s(lang, 'allStructures')],
    [systemUrl(lang, page.system), systemLabel(lang, page.system)],
    ...page.ancestors.map((a): [string, string] => [
      pageUrl(lang, a),
      primaryName(site.bySlug.get(a)!.names, lang),
    ]),
  ];
  const jsonLd = {
    '@context': 'https://schema.org',
    '@type': 'BreadcrumbList',
    itemListElement: [...crumbs, [path, name]].map(([href, label], i) => ({
      '@type': 'ListItem',
      position: i + 1,
      name: label,
      item: abs(href),
    })),
  };

  const ownerSlug = page.type === 'landmark' ? page.ancestors[page.ancestors.length - 1] : undefined;
  const kicker =
    page.type === 'group'
      ? `${t.info.group} · ${systemLabel(lang, page.system)}`
      : page.type === 'landmark'
        ? `${t.info.landmark} · ${systemLabel(lang, page.system)}`
        : systemLabel(lang, page.system);

  const sideLinks =
    page.ids.length === 2
      ? `<span class="sides">${page.ids
          .map((id, i) => `<a href="/?s=${id}">${esc(i === 0 ? t.side.left : t.side.right)}</a>`)
          .join(' · ')}</span>`
      : '';
  const facts: [string, string][] = [
    [t.info.system, `<a href="${systemUrl(lang, page.system)}">${esc(systemLabel(lang, page.system))}</a>`],
  ];
  if (page.regions.length)
    facts.push([t.info.regions, esc(page.regions.map((r) => regionLabel(lang, r)).join(', '))]);
  if (page.sides.length)
    facts.push([
      t.info.side,
      esc(
        page.sides.length === 2
          ? s(lang, 'leftAndRight')
          : page.sides[0] === 'left'
            ? t.side.left
            : t.side.right,
      ),
    ]);
  if (ownerSlug) facts.push([t.info.landmarkOn, link(ctx, lang, ownerSlug)]);
  else if (page.ancestors.length)
    facts.push([t.info.partOf, link(ctx, lang, page.ancestors[page.ancestors.length - 1]!)]);

  const thumb = page.thumbSlug && ctx.hasThumb(page.thumbSlug) ? page.thumbSlug : undefined;
  const thumbOwner = thumb ? site.bySlug.get(thumb)! : undefined;
  const alt =
    thumbOwner && thumb !== page.slug
      ? s(lang, 'landmarkFigure', { name: primaryName(thumbOwner.names, lang) })
      : s(lang, 'figureAlt', { name: fullName });
  const attribution =
    site.data.manifest.attributions[
      site.data.structures.find((st) => st.id === (page.render?.ids[0] ?? ''))?.attribution ?? 'z-anatomy'
    ];
  const figure = thumb
    ? `<figure><img src="/${thumbPath(thumb)}" width="${THUMB_SIZE}" height="${THUMB_SIZE}" alt="${esc(alt)}" fetchpriority="high"><figcaption>${
        thumb !== page.slug ? `${esc(alt)}. ` : ''
      }${esc(s(lang, 'modelCredit'))}: ${esc(attribution?.text ?? 'Z-Anatomy')}</figcaption></figure>`
    : '';

  const sections: string[] = [];
  if (page.definition) sections.push(definitionSection(page.definition, lang));
  const a = page.attachments;
  if (a.origins.length || a.insertions.length || a.originOf.length || a.insertionOf.length) {
    const part = (label: string, list: string[]) =>
      list.length ? `<h3>${esc(label)}</h3>${linkList(ctx, lang, list)}` : '';
    sections.push(
      `<section><h2>${esc(s(lang, 'attachments'))}</h2>${part(cap(t.kind.origin), a.origins)}${part(
        cap(t.kind.insertion),
        a.insertions,
      )}${part(s(lang, 'originOf'), a.originOf)}${part(s(lang, 'insertionOf'), a.insertionOf)}</section>`,
    );
  }
  if (page.parts.length)
    sections.push(`<section><h2>${esc(s(lang, 'parts'))}</h2>${linkList(ctx, lang, page.parts)}</section>`);
  if (page.landmarks.length)
    sections.push(
      `<section><h2>${esc(s(lang, 'landmarks'))}</h2>${refList(ctx, lang, page.landmarks)}</section>`,
    );

  const names = (['la', 'en', 'fr', 'es', 'pt'] as const)
    .filter((l) => page.names[l])
    .map((l) => `<dt>${esc(t.nameLangs[l])}</dt><dd lang="${l}">${esc(page.names[l]!)}</dd>`);
  if (page.synonyms.length)
    names.push(`<dt>${esc(s(lang, 'synonyms'))}</dt><dd>${page.synonyms.map(esc).join(', ')}</dd>`);
  sections.push(`<section><h2>${esc(t.info.names)}</h2><dl class="names">${names.join('')}</dl></section>`);

  const siblings = page.siblings.slice(0, 30);
  if (siblings.length)
    sections.push(`<section><h2>${esc(s(lang, 'related'))}</h2>${linkList(ctx, lang, siblings)}</section>`);

  const body = `<nav class="crumbs" aria-label="Breadcrumb"><ol>${crumbs
    .map(([href, label]) => `<li><a href="${href}">${esc(label)}</a></li>`)
    .join('')}</ol></nav>
<article>
<div class="hero">
<div>
<p class="kicker">${esc(kicker)}</p>
<h1 lang="${nameLang(page.names, lang)}">${esc(name)}</h1>
${second ? `<p class="sub" lang="${lang === 'en' ? 'la' : 'en'}">${esc(second)}</p>` : ''}
<p><a class="btn" href="/?s=${page.openId}">${esc(s(lang, 'openIn3d'))} →</a>${sideLinks}</p>
<dl class="facts">${facts.map(([k, v]) => `<dt>${esc(k)}</dt><dd>${v}</dd>`).join('')}</dl>
</div>
${figure}
</div>
${sections.join('\n')}
</article>`;

  // landmark pages have their own card (their names on their structure's image)
  const card = ctx.hasCard(page.slug)
    ? page.slug
    : page.thumbSlug && ctx.hasCard(page.thumbSlug)
      ? page.thumbSlug
      : undefined;
  return layout(
    {
      lang,
      title: `${fullName} – ${s(lang, 'titleSuffix')} | ${APP_NAME}`,
      description: describe(page, lang),
      path,
      alternates,
      ...(card
        ? {
            image: {
              path: `/${cardPath(card)}`,
              ...CARD_SIZE,
              alt: s(lang, 'figureAlt', { name: fullName }),
            },
          }
        : {}),
      jsonLd,
    },
    body,
    ctx,
  );
}

