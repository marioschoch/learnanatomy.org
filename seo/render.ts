type Block = { kind: 'p'; text: string } | { kind: 'h'; text: string } | { kind: 'ul'; items: string[] };

const HEADING_RE = /^(=+)\s*(.*?)\s*\1$/;

/** Tidy upstream artefacts: "(, pl. femora )" → "(pl. femora)", empty "( )". */
export function tidy(text: string): string {
  return text
    .replace(/\(\s*[,;]?\s*\)/g, '')
    .replace(/\(\s*[,;]\s*/g, '(')
    .replace(/\s+\)/g, ')')
    .replace(/[ \t]{2,}/g, ' ')
    .replace(/ ([,.;:])/g, '$1');
}

/** Split a definition into paragraphs, "== Section ==" headings and "-item" lists. */
export function parseBlocks(text: string): Block[] {
  const blocks: Block[] = [];
  for (const raw of tidy(text).split(/\n{2,}/)) {
    const lines = raw
      .split('\n')
      .map((l) => l.trim())
      .filter(Boolean);
    let para: string[] = [];
    let list: string[] = [];
    const flush = () => {
      if (para.length) blocks.push({ kind: 'p', text: para.join(' ') });
      if (list.length) blocks.push({ kind: 'ul', items: list });
      para = [];
      list = [];
    };
    for (const line of lines) {
      const h = HEADING_RE.exec(line);
      if (h) {
        flush();
        if (h[2]) blocks.push({ kind: 'h', text: h[2] });
      } else if (/^[-•*]\s*\S/.test(line)) {
        if (para.length) flush();
        list.push(line.replace(/^[-•*]\s*/, ''));
      } else {
        if (list.length) flush();
        para.push(line);
      }
    }
    flush();
  }
  return blocks;
}

/**
 * The part of a description shown on the page: for Wikipedia texts the lead (up to the first section heading,
 * at most ~1 500 characters), with a link to the full article; other sources in full.
 */
export function excerpt(def: Definition): { blocks: Block[]; more: boolean } {
  const text = def.text.en ?? Object.values(def.text).find(Boolean) ?? '';
  const blocks = parseBlocks(text);
  if (def.source !== 'Wikipedia') return { blocks, more: false };
  const out: Block[] = [];
  let chars = 0;
  for (const b of blocks) {
    if (b.kind === 'h' && out.length) break;
    if (b.kind === 'h') continue;
    if (chars > 1500) break;
    out.push(b);
    chars += b.kind === 'p' ? b.text.length : b.items.join(' ').length;
  }
  return { blocks: out, more: out.length < blocks.length };
}

function firstParagraph(def: Definition | undefined): string | undefined {
  if (!def) return undefined;
  const p = excerpt(def).blocks.find((b) => b.kind === 'p');
  return p && p.kind === 'p' && p.text.length > 40 ? p.text : undefined;
}

